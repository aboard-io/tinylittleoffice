/**
 * Outline's templates: Blank is the app's own page; these are the rest, each a real outline written by the
 * kernel (so each is canonical and round-trips byte for byte, and the corpus test holds every one). The
 * everyday ones come first (a list to pack, a choice, a plan, a talk), then the work of school and study,
 * then the shapes another app draws (a novel, a book, a company and a family, each handed off), and last the
 * trees you walk by answering yes or no. What each is for is in templates.md.
 */
import type { Template } from '../../kit/app.ts';
import { t } from '../../kit/i18n.ts';
import { column, text, write, type Block, type Dir } from '../../doc/index.ts';
import { docBlock, itemBlock } from './model.ts';

/** An item at a depth: its words (marks and ^[notes] as the format writes them), and how it joins its parent. */
const item = (depth: number, words: string, dir?: Dir, label?: string): Block => itemBlock(depth, text(words), dir, label);
/** A numbered item: it counts with its siblings. */
const num = (depth: number, words: string): Block => itemBlock(depth, text(words), undefined, undefined, undefined, true);
/** Yes and no, as the line from a question to its answer. */
const yes = (depth: number, words: string) => item(depth, words, '->', 'yes');
const no = (depth: number, words: string) => item(depth, words, '->', 'no');
const edge = (from: string, to: string, dir: Dir, label?: string): Block => ({ k: 'edge', from, to, dir, ...(label ? { label } : {}) });
const outline = (title: string, ...blocks: Block[]): string => write({ head: { title }, blocks });

/** A small sheet under an item: its title and a table, formulas and all. */
const sheet = (depth: number, title: string, head: string[], rows: string[][]): Block =>
  docBlock(depth, `sheet\n${write({ head: { title }, blocks: [{ k: 'table', cols: head.map(column), rows }] })}`);

