/**
 * What the command registry (src/kit/core/commands.ts) says, written where people and agents read it: the tables of
 * docs/editing.md between its two markers (every command of every scope but its rows of data, its keys and where it is drawn), and the
 * skill's list of keys (scripts/make-skill.ts reads `skillCommands`). `npm run commands` writes both; a node test
 * (test/commands.test.ts) fails when either is stale. The registry itself is loaded here whole: the kit's and the
 * words' commands, the rows', and each app's commands.ts, in the home page's order.
 *
 *   node scripts/commands.ts           write docs/editing.md's tables and the skill
 *   node scripts/commands.ts --check   write nothing; fail if any of them is stale
 */
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { apps } from '../src/kit/core/apps.ts';
import { labelOf, registered, type Command } from '../src/kit/core/commands.ts';
import '../src/kit/core/keys.ts';
import '../src/kit/text/rows-commands.ts';
import '../src/apps/write/commands.ts';
import '../src/apps/outline/commands.ts';
import '../src/apps/deck/commands.ts';
import '../src/apps/sheet/commands.ts';
import '../src/apps/calc/commands.ts';
import '../src/apps/draw/commands.ts';
import '../src/apps/diagram/commands.ts';
import '../src/apps/anim/commands.ts';
import '../src/apps/cal/commands.ts';
import '../src/apps/trip/commands.ts';
import '../src/apps/board/commands.ts';
import { generate } from './generated.ts';
import { makeSkill, skillOutputs } from './make-skill.ts';

const at = (p: string) => fileURLToPath(new URL(`../${p}`, import.meta.url));

/** Every command, whole. */
export const allCommands = (): Command[] => registered();

/** The scopes in the order the tables list them: the page, the words, the rows, then each app as the home page lists them. */
export function scopes(): { id: string; name: string }[] {
  return [
    { id: 'kit', name: 'Everywhere (the page)' },
    { id: 'text', name: 'Words (wherever words are typed)' },
    { id: 'rows', name: 'Rows chosen whole' },
    ...apps().map((a) => ({ id: a.id, name: a.name })),
  ];
}

const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/</g, '&lt;');
/** Where a command is drawn, in words. */
const whereOf = (c: Command) =>
  [
    ...c.where.map((w) => (w === 'keys-only' ? 'keys only' : w === 'bar' ? (c.menu ? `bar (${c.menu} ▾)` : 'bar') : w.startsWith('menu:') ? `${w.slice(5)} ▾` : w)),
    ...(c.at ? [`at: ${c.at}`] : []),
    ...(c.document && !c.where.includes('drawer') ? ['drawer on a phone'] : []),
  ].join(', ');
const keysOf = (c: Command) =>
  c.keys
    ? c.keys
        .split(' / ')
        .map((k) => `\`${k}\``)
        .join(', ')
    : '';

/** docs/editing.md's generated part: a table a scope. */
export function editingTables(): string {
  const all = allCommands();
  const out = ['<!-- commands:begin (generated by `npm run commands` from the registry, src/kit/core/commands.ts: do not edit by hand) -->', ''];
  for (const s of scopes()) {
    const cmds = all.filter((c) => c.scope === s.id && !c.menu && !c.data);
    if (!cmds.length) continue;
    out.push(`### ${esc(s.name)} (\`${s.id}\`)`, '', '| Keys | Command | Where |', '|---|---|---|');
    for (const c of cmds) out.push(`| ${keysOf(c)} | ${esc(labelOf(c))} | ${esc(whereOf(c))} |`);
    out.push('');
  }
  out.push('<!-- commands:end -->');
  return out.join('\n');
}

/** The skill's keys: a line an app, the keys and what they do (an agent driving a browser reads these). */
export function skillCommands(): string {
  const all = allCommands();
  return scopes()
    .map((s) => {
      const keyed = all.filter((c) => c.scope === s.id && c.keys && !c.data);
      return keyed.length
        ? `- **${s.name}**: ${keyed
            .map(
              (c) =>
                `${c
                  .keys!.split(' / ')
                  .map((k) => `\`${k}\``)
                  .join('/')} ${labelOf(c).replace(/…$/, '')}`,
            )
            .join('; ')}.`
        : '';
    })
    .filter(Boolean)
    .join('\n');
}

const BEGIN = '<!-- commands:begin';
const END = '<!-- commands:end -->';
/** docs/editing.md with its generated part as the registry says it. */
function editingDoc(text = readFileSync(at('docs/editing.md'), 'utf8')): string {
  const i = text.indexOf(BEGIN);
  const j = text.indexOf(END);
  if (i < 0 || j < i) throw new Error('docs/editing.md: no commands markers');
  return text.slice(0, i) + editingTables() + text.slice(j + END.length);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  generate({ 'docs/editing.md': editingDoc(), ...skillOutputs(await makeSkill()) }, 'npm run commands');
}
